#!/usr/bin/env python3
"""Write the user guide's demo projects.

tests/fixtures/Guide demo.uzx, for Studio: 18 PSG clips on 3 AY tracks, also for checking clip headers by eye.
Each clip has its own step of the clip colour palette (PsgClip::colourForTrackIndex), and its own key. Clips on
the first track are 4 s long, on the second 2 s and on the third 1 s, so headers shorten in different ways; one
clip per track plays at 25 fps in the 50 fps project, so its header shows a warning.

tests/fixtures/Turbo Sound demo.uzx, for the Player: what opening a two-chip Turbo Sound set gives, one clip per
track, both chips in A minor, each playing its own part."""

import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FIXTURE = ROOT / "tests/fixtures/Guide demo.uzx"
PLAYER_FIXTURE = ROOT / "tests/fixtures/Turbo Sound demo.uzx"
TRACKS = (("Lead", 4.0), ("Bass", 2.0), ("Arp", 1.0))
CLIPS_PER_TRACK = 6
FPS, ZX_CLOCK = 50, 1773400
NOTE_NAMES = ("C", "C#", "D", "D#", "E", "F", "F#", "G", "G#", "A", "A#", "B")


def oklch_to_argb(L, C, H):
    """As Oklch::toColour() in src/util/Oklch.h; C 0.12 at L 0.72 is inside sRGB for every hue."""
    h = math.radians(H)
    a, b = C * math.cos(h), C * math.sin(h)
    l = (L + 0.3963377774 * a + 0.2158037573 * b) ** 3
    m = (L - 0.1055613458 * a - 0.0638541728 * b) ** 3
    s = (L - 0.0894841775 * a - 1.2914855480 * b) ** 3
    linear = (4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s,
              -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s,
              -0.0041960863 * l - 0.7034186147 * m + 1.7076147010 * s)
    srgb = [12.92 * x if x <= 0.0031308 else 1.055 * x ** (1 / 2.4) - 0.055 for x in linear]
    return "ff" + "".join(f"{round(min(1.0, max(0.0, x)) * 255):02x}" for x in srgb)


def palette(step):
    """PsgClip::colourForTrackIndex(step)."""
    return oklch_to_argb(0.72, 0.12, (140.0 + (step % 18) * 20.0) % 360.0)


def period(midi):
    return round(ZX_CLOCK / (16 * 440.0 * 2 ** ((midi - 69) / 12)))


def frames(tonic, minor, count, shift=0, octave=0):
    """A melody on A over a bass on B and a held third on C, all in the key, a note every 12 frames;
    shift starts the melody further along, octave moves the whole part."""
    scale = (0, 2, 3, 5, 7, 8, 10) if minor else (0, 2, 4, 5, 7, 9, 11)
    melody = (0, 2, 4, 7, 4, 2, 1, 0)
    root = 60 + 12 * octave + tonic
    third = root + scale[2]
    result = []
    for i in range(count):
        attributes = {}
        step, age = divmod(i, 12)
        if i == 0:
            attributes.update(ta=1, tb=1, tc=1, na=0, nb=0, nc=0, ea=0, eb=0, ec=0, vc=7, pc=period(third))
        if age == 0:
            degree = melody[(step + shift) % len(melody)]
            note = root + 12 * (degree // 7) + scale[degree % 7]
            attributes.update(pa=period(note))
            if step % 4 == 0:
                attributes.update(vb=10, pb=period(root - 12 - 12 * (step // 4 % 2)))
        if age % 2 == 0:
            attributes.update(va=max(4, 14 - age // 2))
        if step % 4 == 0 and age % 6 == 0 and i:
            attributes.update(vb=max(4, 10 - age // 6))
        line = " ".join(f'{k}="{v}"' for k, v in attributes.items())
        result.append(f'        <FRAME i="{i}"{" " + line if line else ""} />')
    return result


def clip_xml(ids, title, start, seconds, fps, colour, body):
    return f'''    <PSGCLIP name="{title}" start="{start}" length="{seconds}" offset="0.0" id="{next(ids)}" currentTake="0" speed="1.0" colour="{colour}">
      <AUTOMATIONCURVES />
      <QUANTISATION />
      <GROOVE />
      <SEQUENCE ver="1" channelNumber="1" />
      <PSG ver="1" frameRate="{FPS}.0" framesPerBeat="{fps / 2}" channelNumber="1">
{body}
      </PSG>
    </PSGCLIP>'''


def track_xml(ids, name, clips, comment, height):
    return f'''  <TRACK id="{next(ids)}" name="{name}">
    <!-- {comment} -->
    <MODIFIERS />
    <OUTPUTDEVICES>
      <DEVICE name="(default audio output)" />
    </OUTPUTDEVICES>
    <CLIPSLOTS />
    <PLUGIN type="aychip" windowLocked="1" id="{next(ids)}" enabled="1" midi="1" chip="AY" clock="1.7734" noDC="1" monitor="0" volume="0.5" layout="ACB" stereo="0.5" channelA="1" channelB="1" channelC="1" toneA="1" toneB="1" toneC="1" noiseA="1" noiseB="1" noiseC="1" envelopeA="1" envelopeB="1" envelopeC="1" windowSamples="1024" gain="1.0" triggerMode="RisingEdge" triggerLevel="0.0" remapOnTempoChange="1">
      <MODIFIERASSIGNMENTS />
    </PLUGIN>
    <PLUGIN type="volume" id="{next(ids)}" enabled="1" remapOnTempoChange="1">
      <MODIFIERASSIGNMENTS />
    </PLUGIN>
    <PLUGIN type="level" id="{next(ids)}" enabled="1" />
{chr(10).join(clips)}
    <VIEWSTATE height="{height}" />
  </TRACK>'''


def edit_xml(tracks, description):
    return f'''<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/make_guide_fixture.py: {description}. -->
<EDIT appVersion="0.5.0" projectFps="{FPS}.0" timecodeDisplayMode="barsBeatsFrames" timecodeFormat="beats">
  <TRANSPORT endToEnd="1" />
  <PITCHSEQUENCE>
    <PITCH startBeat="0.0" pitch="60" />
  </PITCHSEQUENCE>
  <TEMPOSEQUENCE>
    <TEMPO startBeat="0.0" bpm="120.0" curve="1.0" />
    <TIMESIG numerator="4" denominator="4" startBeat="0.0" />
  </TEMPOSEQUENCE>
  <VIDEO />
  <CLICKTRACK level="0.6000000238418579" />
  <MASTERVOLUME>
    <PLUGIN type="volume" volume="0.6376281380653381" id="1001" enabled="1">
      <MODIFIERASSIGNMENTS />
    </PLUGIN>
  </MASTERVOLUME>
  <RACKS />
  <MASTERPLUGINS />
  <INPUTDEVICES />
  <TRACKCOMPS />
  <ARRANGERTRACK name="Arranger" id="1006" />
  <CHORDTRACK name="Chord" id="1008" />
  <MARKERTRACK id="1002" name="Marker" />
  <TEMPOTRACK name="Global" id="1007">
    <MODIFIERS />
  </TEMPOTRACK>
  <MASTERTRACK name="Master" id="1009">
    <MODIFIERS />
  </MASTERTRACK>
{chr(10).join(tracks)}
  <EDITVIEWSTATE headersWidth="180" />
</EDIT>
'''


def studio_demo():
    ids = iter(range(1100, 10000))
    tracks = []
    for t, (name, seconds) in enumerate(TRACKS):
        clips = []
        for c in range(CLIPS_PER_TRACK):
            index = t * CLIPS_PER_TRACK + c
            slow = c == 2  # plays at 25 fps: the header warns "25 @ 50 fps"
            fps = FPS // 2 if slow else FPS
            count = round(seconds * fps)
            tonic, minor = (index * 7) % 12, index % 2 == 1  # around the circle of fifths
            title = f"{name} {c + 1}" + (" with a long name that gets shortened" if c == 4 else "")
            body = "\n".join(frames(tonic, minor, count))
            clips.append(clip_xml(ids, title, c * seconds * 1.25, seconds, fps, palette(index), body))
        key_names = ", ".join(f"{NOTE_NAMES[(i * 7) % 12]}{'m' if i % 2 else ''}" for i in range(t * 6, t * 6 + 6))
        tracks.append(track_xml(ids, name, clips, key_names, 130))
    return edit_xml(tracks, "18 clips on 3 tracks, one palette colour and key each")


def player_demo():
    ids = iter(range(1100, 10000))
    seconds = 16.0
    tracks = []
    for chip, (shift, octave) in enumerate(((0, 0), (4, -1))):  # the second chip answers an octave lower
        name = f"{PLAYER_FIXTURE.stem}.{chip + 1}"
        body = "\n".join(frames(9, True, round(seconds * FPS), shift, octave))
        clip = clip_xml(ids, name, 0.0, seconds, FPS, palette(chip), body)
        tracks.append(track_xml(ids, name, [clip], "A minor", 300))
    return edit_xml(tracks, "a two-chip Turbo Sound tune, one clip per track")


def main():
    for path, xml in ((FIXTURE, studio_demo()), (PLAYER_FIXTURE, player_demo())):
        path.write_text(xml)
        print(f"Wrote {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
